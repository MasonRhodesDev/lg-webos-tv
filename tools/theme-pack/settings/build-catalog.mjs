#!/usr/bin/env node
// Turns the catalog (settings/catalog.json and its category files) into ui/Look/settings/catalog.js, a `.pragma
// library` the compositor's QML loads without file I/O. Run it after changing the catalog; a test checks the output
// is current.
//   node settings/build-catalog.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'ui', 'Look', 'settings', 'catalog.js');

// Items by id, built once when the library loads: the first one with an API of its own (a row that only opens a page
// shares its id with the setting that page holds). Every item is also reachable as "Page/id".
const INDEX = `var items = (function () {
    var out = {};
    for (var i = 0; i < catalog.order.length; i++) {
        var p = catalog.pages[catalog.order[i]];
        for (var j = 0; j < p.items.length; j++) {
            var it = p.items[j];
            out[p.id + "/" + it.id] = it;
            if (!(it.api && it.api.none) && !out[it.id]) out[it.id] = it;
        }
    }
    return out;
})();
`;

export function build() {
  const index = JSON.parse(readFileSync(join(here, 'catalog.json'), 'utf8'));
  const keep = ['id', 'meaning', 'tier', 'api', 'type', 'domain', 'dimension', 'confirm', 'opens', 'visibleWhen', 'region'];
  const pages = {}, order = [];
  for (const c of index.categories) {
    const data = JSON.parse(readFileSync(join(here, c.file), 'utf8'));
    for (const p of data.pages) {
      const list = p.items.map((it) => {
        const o = {};
        for (const k of keep) if (it[k] !== undefined && it[k] !== null) o[k] = it[k];
        return o;
      });
      pages[p.id] = { id: p.id, category: c.id, meaning: p.meaning, lgPath: p.lgPath, items: list };
      if (p.region) pages[p.id].region = p.region;
      order.push(p.id);
    }
  }
  const targets = {};
  for (const [name, where] of Object.entries(index.lgTargets.map)) targets[name] = Array.isArray(where) ? where : [where];
  const catalog = { categories: index.categories.map((c) => ({ id: c.id, meaning: c.meaning, lgTarget: c.lgTarget })),
    pages, order, targets };
  return '.pragma library\n// Generated by settings/build-catalog.mjs from settings/*.json. Do not edit.\nvar catalog = ' +
    JSON.stringify(catalog) + ';\n' + INDEX;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = build();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(out, 'utf8'); } catch (e) { /* missing */ }
    if (cur !== text) { console.error(out + ' is stale: run node settings/build-catalog.mjs'); process.exit(1); }
  } else {
    writeFileSync(out, text);
    console.log('wrote ' + out + ' (' + text.length + ' bytes)');
  }
}
